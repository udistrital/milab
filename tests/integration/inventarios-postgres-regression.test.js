async function initializeInventoryApprovalSchema(db) {
  await db.query(`
    CREATE TABLE coordinador (
      documento VARCHAR(50) PRIMARY KEY,
      nombre TEXT NOT NULL,
      activo BOOLEAN NOT NULL DEFAULT TRUE
    );
    CREATE TABLE coordinador_facultad_alcance (
      coordinador_documento_id VARCHAR(50) NOT NULL REFERENCES coordinador(documento),
      facultad_id INT NOT NULL REFERENCES dependencia_facultad(dependencia_facultad_id),
      activo BOOLEAN NOT NULL DEFAULT TRUE,
      PRIMARY KEY (coordinador_documento_id, facultad_id)
    );
    CREATE TABLE inventario_carga (
      id INT PRIMARY KEY,
      ual_id INT NOT NULL REFERENCES ual(ual_id),
      tipo_inventario TEXT NOT NULL,
      estado TEXT NOT NULL,
      coordinador_documento VARCHAR(50) NOT NULL REFERENCES coordinador(documento),
      facultad_id INT NOT NULL REFERENCES dependencia_facultad(dependencia_facultad_id),
      declaracion_sin_inventario BOOLEAN NOT NULL DEFAULT FALSE,
      creada_por_documento TEXT,
      total_filas INT NOT NULL DEFAULT 1,
      fecha_resolucion TIMESTAMPTZ
    );
    CREATE TABLE coordinador_ual_encargado (
      ual_id INT PRIMARY KEY REFERENCES ual(ual_id),
      coordinador_documento VARCHAR(50) NOT NULL REFERENCES coordinador(documento),
      carga_id INT REFERENCES inventario_carga(id)
    );
    CREATE TABLE inventario (
      id INT PRIMARY KEY,
      tipo_inventario TEXT NOT NULL,
      placa TEXT,
      nombre_bien TEXT,
      atributos JSONB NOT NULL DEFAULT '{}'::jsonb,
      espacio_fisico TEXT,
      carga_id INT REFERENCES inventario_carga(id),
      estado_aprobacion TEXT NOT NULL DEFAULT 'pendiente',
      disponible_prestamo BOOLEAN NOT NULL DEFAULT FALSE,
      fecha_modificacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    ALTER TABLE equipo
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE equipo ADD COLUMN inventario_id INT UNIQUE REFERENCES inventario(id);
    ALTER TABLE equipo ADD COLUMN estado TEXT NOT NULL DEFAULT 'disponible';
    CREATE TABLE inventario_carga_fila (
      id INT PRIMARY KEY,
      carga_id INT NOT NULL REFERENCES inventario_carga(id),
      numero_fila INT NOT NULL,
      inventario_id INT REFERENCES inventario(id),
      estado TEXT NOT NULL
    );
    CREATE TABLE inventario_estado_laboratorio (
      ual_id INT NOT NULL REFERENCES ual(ual_id),
      tipo_inventario TEXT NOT NULL,
      estado TEXT NOT NULL,
      sin_inventario BOOLEAN NOT NULL DEFAULT FALSE,
      carga_id INT REFERENCES inventario_carga(id),
      aprobado_por_documento VARCHAR(50) REFERENCES coordinador(documento),
      fecha_aprobacion TIMESTAMPTZ,
      fecha_modificacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (ual_id, tipo_inventario)
    );
    CREATE TABLE inventario_auditoria (
      id BIGSERIAL PRIMARY KEY,
      carga_id INT REFERENCES inventario_carga(id),
      inventario_id INT REFERENCES inventario(id),
      ual_id INT REFERENCES ual(ual_id),
      actor_documento TEXT,
      actor_rol TEXT,
      accion TEXT NOT NULL,
      detalle JSONB NOT NULL DEFAULT '{}'::jsonb
    );
    INSERT INTO coordinador (documento, nombre) VALUES ('coord-1', 'Coordinador Uno');
    INSERT INTO coordinador_facultad_alcance (coordinador_documento_id, facultad_id)
    VALUES ('coord-1', 1);
    INSERT INTO inventario_carga (
      id, ual_id, tipo_inventario, estado, coordinador_documento, facultad_id, creada_por_documento
    ) VALUES (8, 11, 'equipo_arka', 'pendiente_aprobacion', 'coord-1', 1, 'lab-1');
    INSERT INTO inventario (
      id, tipo_inventario, placa, nombre_bien, atributos, espacio_fisico, carga_id
    ) VALUES (
      41, 'equipo_arka', 'ARKA-001', 'Microscopio', '{"marca":"Marca","modelo":"Modelo"}',
      'Laboratorio uno', 8
    );
    INSERT INTO inventario_carga_fila (id, carga_id, numero_fila, inventario_id, estado)
    VALUES (31, 8, 2, 41, 'pendiente_aprobacion');
  `);
}

function buildInventoryApproverApp(db) {
  const sessionHarness = createSessionHarness({
    user: createUser({
      id: 99,
      tipo: 'admin',
      roles: ['admin'],
      documento: 'admin-1',
      documento_real: 'admin-1',
    }),
  });
  const loaded = loadModuleWithStubs({
    entryPath: routePath,
    stubs: [
      [dbPath, db],
      [authPath, { requireRoles: () => (req, res, next) => next() }],
    ],
    purgePaths: [routePath],
  });
  const app = express();
  app.use(express.json());
  app.use(express.urlencoded({ extended: true }));
  app.use((req, res, next) => {
    sessionHarness.attach(req);
    res.render = (view, locals) => res.status(res.statusCode || 200).json({ view, locals });
    next();
  });
  app.use(loaded.loaded);
  app.use((error, req, res, next) => {
    if (res.headersSent) return next(error);
    return res.status(error?.status || 500).json({
      error: error?.message || 'Unexpected test error',
    });
  });

  return { app, restore: loaded.restore };
}

test(
  'PostgreSQL approval records the assigned coordinator accepted by the foreign key',
  {
    skip: testDatabaseConfigured
      ? false
      : 'Set MILAB_CAPACITACION_TEST_DATABASE_URL or MILAB_CAPACITACION_TEST_USE_APP_DB=true to run PostgreSQL regressions',
  },
  async () => {
    const fixture = await createPostgresFixture();
    let loaded;

    try {
      await initializeInventoryApprovalSchema(fixture.db);
      loaded = buildInventoryApproverApp(fixture.db);

      const response = await request(loaded.app)
        .post('/aprobaciones/8/resolver')
        .send({ decision: 'aprobar', comentario: 'Inventario validado' });

      assert.equal(response.status, 302, JSON.stringify(response.body));
      const approvalState = await fixture.db.query(
        `SELECT estado, aprobado_por_documento
           FROM inventario_estado_laboratorio
          WHERE ual_id = $1 AND tipo_inventario = $2`,
        [11, 'equipo_arka']
      );
      assert.deepEqual(
        [approvalState.rows[0].estado, approvalState.rows[0].aprobado_por_documento],
        ['aprobado', 'coord-1']
      );
      const equipment = await fixture.db.query(
        `SELECT estado_aprobacion, disponible_prestamo
           FROM inventario
          WHERE id = $1`,
        [41]
      );
      assert.deepEqual(
        [equipment.rows[0].estado_aprobacion, equipment.rows[0].disponible_prestamo],
        ['aprobado', true]
      );
      const loanableEquipment = await fixture.db.query(
        'SELECT inventario_id, estado FROM equipo WHERE inventario_id = $1',
        [41]
      );
      assert.deepEqual(
        [loanableEquipment.rows[0].inventario_id, loanableEquipment.rows[0].estado],
        [41, 'disponible']
      );
    } finally {
      loaded?.restore();
      await fixture.cleanup();
    }
  }
);
