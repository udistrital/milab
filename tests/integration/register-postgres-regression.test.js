async function initializeRegistrationSchema(db) {
  await db.query(`
    ALTER TABLE usuario ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE usuario ALTER COLUMN id RESTART WITH 1000;
    ALTER TABLE usuario ALTER COLUMN tipo DROP NOT NULL;
    ALTER TABLE usuario ADD COLUMN nombre TEXT;
    ALTER TABLE usuario ADD COLUMN correo TEXT;
    ALTER TABLE usuario ADD COLUMN estado TEXT;
    ALTER TABLE usuario ADD COLUMN carrera TEXT;
    ALTER TABLE usuario ADD COLUMN fecha_modificacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP;

    CREATE TABLE rol (
      id INT PRIMARY KEY,
      nombre TEXT NOT NULL UNIQUE
    );
    CREATE TABLE usuario_rol (
      usuario_id INT NOT NULL REFERENCES usuario(id),
      rol_id INT NOT NULL REFERENCES rol(id),
      activo BOOLEAN NOT NULL DEFAULT TRUE,
      fecha_modificacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      PRIMARY KEY (usuario_id, rol_id)
    );
    INSERT INTO rol (id, nombre)
    VALUES (1, 'estudiante'), (2, 'docente'), (3, 'laboratorista');
  `);
}

