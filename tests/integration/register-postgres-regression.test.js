async function initializeOperationalRegistrationSchema(db) {
  await db.query(`
    CREATE TABLE coordinador (
      documento VARCHAR(50) PRIMARY KEY,
      correo TEXT,
      nombre TEXT NOT NULL,
      nombre_u TEXT,
      usuario_id INT,
      activo BOOLEAN NOT NULL DEFAULT TRUE
    );
    CREATE TABLE coordinador_facultad_alcance (
      coordinador_documento_id VARCHAR(50) NOT NULL REFERENCES coordinador(documento),
      facultad_id INT NOT NULL REFERENCES dependencia_facultad(dependencia_facultad_id),
      activo BOOLEAN NOT NULL DEFAULT TRUE,
      PRIMARY KEY (coordinador_documento_id, facultad_id)
    );
    CREATE TABLE laboratorista (
      documento VARCHAR(50) PRIMARY KEY,
      nombre TEXT NOT NULL CHECK (nombre <> 'Forzar fallo'),
      n_usuario TEXT NOT NULL,
      correo TEXT NOT NULL UNIQUE,
      contrato TEXT,
      usuario_id BIGINT NOT NULL REFERENCES usuario(id)
    );
    CREATE TABLE laboratorista_ual (
      laboratorista_documento_id VARCHAR(50) NOT NULL REFERENCES laboratorista(documento),
      ual_id INT NOT NULL REFERENCES ual(ual_id),
      PRIMARY KEY (laboratorista_documento_id, ual_id)
    );
    INSERT INTO coordinador (documento, correo, nombre, nombre_u)
    VALUES ('coord-900', 'coordinador@udistrital.edu.co', 'Coordinador de prueba', '900');
    INSERT INTO coordinador_facultad_alcance (coordinador_documento_id, facultad_id)
    VALUES ('coord-900', 1);
  `);
}

