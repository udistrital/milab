test(
  'PostgreSQL persists a verified docente account and activates its role exactly once',
  {
    skip: testDatabaseConfigured
      ? false
      : 'Set MILAB_CAPACITACION_TEST_DATABASE_URL or MILAB_CAPACITACION_TEST_USE_APP_DB=true to run PostgreSQL regressions',
  },
  async () => {
    const fixture = await createPostgresFixture();
    const mailMessages = [];
    let loaded;

    try {
      await initializeRegistrationSchema(fixture.db);
      const sessionHarness = teacherRegistrationSession();
      loaded = buildRegisterApp(fixture.db, sessionHarness, async (message) => {
        mailMessages.push(message);
        return { accepted: true };
      });

      const verification = await request(loaded.app).post('/email_verification').type('form').send({
        tipo_usuario: 'docente',
        correo: 'docente.prueba@udistrital.edu.co',
        password: 'Abcd1234!',
        confirmar_password: 'Abcd1234!',
      });
      assert.equal(verification.status, 200);
      assert.equal(verification.body.view, 'home/email_verification');
      assert.equal(mailMessages.length, 0);

      const sentCode = await request(loaded.app).post('/enviar-codigo').send({});
      assert.equal(sentCode.status, 200);
      assert.equal(mailMessages.length, 1);
      const verificationCode = sessionHarness.state.usuario_no_verificado.codigoVerificacion;
      assert.match(verificationCode, /^\d{6}$/);
      assert.ok(mailMessages[0].text.includes(verificationCode));

      const invalidCode = await request(loaded.app)
        .post('/create_account')
        .type('form')
        .send({ codigo_verificacion: '000000' });
      assert.equal(invalidCode.body.view, 'home/message_error');
      const notYetCreated = await fixture.db.query('SELECT id FROM usuario WHERE documento = $1', [
        'docente-reg-1001',
      ]);
      assert.equal(notYetCreated.rows.length, 0);

      const account = await request(loaded.app)
        .post('/create_account')
        .type('form')
        .send({ codigo_verificacion: verificationCode });
      assert.equal(account.status, 200);
      assert.equal(account.body.view, 'home/login_2');
      assert.equal(sessionHarness.state.usuario_no_verificado, undefined);

      const persisted = await fixture.db.query(
        `SELECT u.id, u.nombre, u.correo, ur.activo, r.nombre AS rol
           FROM usuario u
           JOIN usuario_rol ur ON ur.usuario_id = u.id
           JOIN rol r ON r.id = ur.rol_id
          WHERE u.documento = $1`,
        ['docente-reg-1001']
      );
      assert.deepEqual(
        persisted.rows.map((row) => [row.nombre, row.correo, row.activo, row.rol]),
        [['Docente de Prueba', 'docente.prueba@udistrital.edu.co', true, 'docente']]
      );

      const duplicateSession = teacherRegistrationSession();
      const duplicateApp = buildRegisterApp(fixture.db, duplicateSession, async () => {
        throw new Error('Duplicate registration must not send verification email.');
      });
      try {
        const duplicate = await request(duplicateApp.app)
          .post('/email_verification')
          .type('form')
          .send({
            tipo_usuario: 'docente',
            correo: 'docente.prueba@udistrital.edu.co',
            password: 'Abcd1234!',
            confirmar_password: 'Abcd1234!',
          });
        assert.equal(duplicate.status, 200);
        assert.match(
          duplicate.body.locals?.error || '',
          /ya existe/i,
          JSON.stringify(duplicate.body)
        );
        assert.equal(duplicateSession.state.usuario_no_verificado, undefined);
      } finally {
        duplicateApp.restore();
      }
    } finally {
      loaded?.restore();
      await fixture.cleanup();
    }
  }
);

test(
  'PostgreSQL rolls back the user when role assignment fails during account creation',
  {
    skip: testDatabaseConfigured
      ? false
      : 'Set MILAB_CAPACITACION_TEST_DATABASE_URL or MILAB_CAPACITACION_TEST_USE_APP_DB=true to run PostgreSQL regressions',
  },
  async () => {
    const fixture = await createPostgresFixture();
    let loaded;

    try {
      await initializeRegistrationSchema(fixture.db);
      await fixture.db.query(`
        CREATE FUNCTION reject_docente_role_assignment()
        RETURNS TRIGGER
        LANGUAGE plpgsql
        AS $$
        BEGIN
          IF NEW.rol_id = (SELECT id FROM rol WHERE nombre = 'docente') THEN
            RAISE EXCEPTION 'Role assignment rejected for regression test';
          END IF;
          RETURN NEW;
        END;
        $$;
        CREATE TRIGGER trg_reject_docente_role_assignment
        BEFORE INSERT ON usuario_rol
        FOR EACH ROW EXECUTE FUNCTION reject_docente_role_assignment();
      `);
      const sessionHarness = createSessionHarness({
        usuario_no_verificado: {
          documento: 'docente-reg-fail-1002',
          codigo: null,
          nombre: 'Docente de Fallo',
          correo: 'docente-fail@udistrital.edu.co',
          carrera: null,
          estado: 'ACTIVO',
          password: 'Abcd1234!',
          tipo: 'docente',
          codigoVerificacion: '654321',
        },
      });
      loaded = buildRegisterApp(fixture.db, sessionHarness, async () => {
        throw new Error('No email should be sent when persistence fails.');
      });

      const response = await request(loaded.app)
        .post('/create_account')
        .type('form')
        .send({ codigo_verificacion: '654321' });
      assert.equal(response.status, 200);
      assert.equal(response.body.view, 'home/message_error');

      const orphanedAccount = await fixture.db.query(
        'SELECT id FROM usuario WHERE documento = $1',
        ['docente-reg-fail-1002']
      );
      assert.equal(orphanedAccount.rows.length, 0);
    } finally {
      loaded?.restore();
      await fixture.cleanup();
    }
  }
);

test(
  'PostgreSQL operational registration commits the laboratorista, role, lab scope, then sends welcome email',
  {
    skip: testDatabaseConfigured
      ? false
      : 'Set MILAB_CAPACITACION_TEST_DATABASE_URL or MILAB_CAPACITACION_TEST_USE_APP_DB=true to run PostgreSQL regressions',
  },
  async () => {
    const fixture = await createPostgresFixture();
    const mailMessages = [];
    let stateAtEmail;
    let loaded;

    try {
      await initializeRegistrationSchema(fixture.db);
      await initializeOperationalRegistrationSchema(fixture.db);
      loaded = buildRegisterLabsApp(
        fixture.db,
        { tipo: 'admin', roles: ['admin'], documento: 'admin-test' },
        async (mail) => {
          mailMessages.push(mail);
          const result = await fixture.db.query(
            `SELECT l.documento, l.usuario_id, ual.ual_id
               FROM laboratorista l
               JOIN laboratorista_ual ual ON ual.laboratorista_documento_id = l.documento
              WHERE l.documento = $1`,
            ['lab-reg-2001']
          );
          stateAtEmail = result.rows;
        }
      );

      const response = await request(loaded.app)
        .post('/')
        .type('form')
        .send({
          nombre: 'Laboratorista de prueba',
          documento: 'lab-reg-2001',
          correo: 'lab-reg-2001@udistrital.edu.co',
          contrato: 'CPS-2026',
          facultad_id: '1',
          ual_ids: ['11'],
          coordinador_documento: 'coord-900',
        });

      assert.equal(response.status, 200);
      assert.equal(response.body.view, 'home/message_success');
      assert.equal(mailMessages.length, 1);
      assert.equal(mailMessages[0].to, 'lab-reg-2001@udistrital.edu.co');
      assert.equal(stateAtEmail.length, 1);
      assert.equal(stateAtEmail[0].ual_id, 11);

      const persisted = await fixture.db.query(
        `SELECT l.documento, l.correo, r.nombre AS rol, ual.ual_id
           FROM laboratorista l
           JOIN usuario_rol ur ON ur.usuario_id = l.usuario_id AND ur.activo = TRUE
           JOIN rol r ON r.id = ur.rol_id
           JOIN laboratorista_ual ual ON ual.laboratorista_documento_id = l.documento
          WHERE l.documento = $1`,
        ['lab-reg-2001']
      );
      assert.deepEqual(
        persisted.rows.map((row) => [row.documento, row.correo, row.rol, row.ual_id]),
        [['lab-reg-2001', 'lab-reg-2001@udistrital.edu.co', 'laboratorista', 11]]
      );

      const emailFailureApp = buildRegisterLabsApp(
        fixture.db,
        { tipo: 'admin', roles: ['admin'], documento: 'admin-test' },
        async () => {
          throw new Error('SMTP unavailable');
        }
      );
      try {
        const emailFailureResponse = await request(emailFailureApp.app)
          .post('/')
          .type('form')
          .send({
            nombre: 'Laboratorista sin correo',
            documento: 'lab-reg-2003',
            correo: 'lab-reg-2003@udistrital.edu.co',
            contrato: 'CPS-2026',
            facultad_id: '1',
            ual_ids: ['11'],
            coordinador_documento: 'coord-900',
          });

        assert.equal(emailFailureResponse.status, 200);
        assert.equal(emailFailureResponse.body.view, 'home/message_success');
        assert.match(
          emailFailureResponse.body.locals.message2,
          /cuenta fue creada.*no se pudo enviar/i
        );
        const persistedWithoutEmail = await fixture.db.query(
          `SELECT documento FROM laboratorista WHERE documento = $1`,
          ['lab-reg-2003']
        );
        assert.equal(persistedWithoutEmail.rows.length, 1);
      } finally {
        emailFailureApp.restore();
      }
    } finally {
      loaded?.restore();
      await fixture.cleanup();
    }
  }
);

