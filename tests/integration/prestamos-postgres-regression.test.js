function buildLoanApp(db, user) {
  const sessionHarness = createSessionHarness({
    user: createUser(user),
  });
  return buildApp({
    entryPath: routePath,
    sessionHarness,
    stubs: [
      [
        authPath,
        {
          requirePermissions: () => (req, res, next) => next(),
          requireRoles: () => (req, res, next) => next(),
          renderAuthError: (res, payload) => res.status(403).json(payload),
        },
      ],
      [dbPath, db],
      [
        permissionsPath,
        {
          APP_PERMISSIONS: new Proxy({}, { get: (_, key) => String(key) }),
          hasPermission: () => true,
        },
      ],
      [
        moduleAccessPath,
        {
          getPrestamosModuleAccess: async () => ({
            blocked: false,
            role: user.roles[0],
            allowedFacultyIds: [],
          }),
        },
      ],
      [
        operationalRolesPath,
        {
          fetchOperationalRoleScopeByUser: async () => ({ facultyIds: [], ualIds: [] }),
        },
      ],
      [notificationsPath, { sendEmailNotification: async () => ({ success: true }) }],
      [
        certificationValidationPath,
        {
          getCursosActivosDeEquipo: async () => [],
          validarCertificacionesParaReserva: async () => ({ permitir: true, cursos: [] }),
        },
      ],
    ],
    purgePaths: [routePath],
  });
}

test(
  'PostgreSQL persists a loan request through approval, delivery, and return',
  {
    skip: testDatabaseConfigured
      ? false
      : 'Set MILAB_CAPACITACION_TEST_DATABASE_URL or MILAB_CAPACITACION_TEST_USE_APP_DB=true to run PostgreSQL regressions',
  },
  async () => {
    const fixture = await createPostgresFixture();
    let studentApp;
    let adminApp;

    try {
      await initializeLoanSchema(fixture.db);
      studentApp = buildLoanApp(fixture.db, {
        id: 55,
        documento: 'student-1',
        tipo: 'estudiante',
        roles: ['estudiante'],
      });
      adminApp = buildLoanApp(fixture.db, {
        id: 99,
        documento: 'admin-1',
        tipo: 'admin',
        roles: ['admin'],
      });

      const reservation = await request(studentApp.app).post('/solicitudes/crear').send({
        equipo_id: '5',
        fecha_inicio: '2999-12-31T10:00',
        fecha_fin: '2999-12-31T11:00',
        justificacion_academica: 'Practica de laboratorio de ciencias',
        categoria_practica: 'academica',
        firma_digital: 'Acepto el reglamento',
      });
      assert.equal(reservation.status, 200, JSON.stringify(reservation.body));
      assert.equal(reservation.body.success, true);
      const requestId = reservation.body.solicitud.id;

      const approval = await request(adminApp.app)
        .post(`/gestion-solicitudes/${requestId}/aprobar`)
        .send({});
      assert.equal(approval.status, 200);
      assert.equal(approval.body.success, true);
      const approved = await fixture.db.query(
        'SELECT estado FROM solicitud_prestamo WHERE id = $1',
        [requestId]
      );
      assert.equal(approved.rows[0].estado, 'aprobado');

      const delivery = await request(adminApp.app)
        .post(`/entrega-equipos/${requestId}/marcar-prestado`)
        .send({ condicion_entrega: 'Equipo entregado en buen estado' });
      assert.equal(delivery.status, 200);
      assert.equal(delivery.body.success, true);
      const active = await fixture.db.query(
        `SELECT sp.estado, e.estado AS equipo_estado, ee.condicion_entrega
           FROM solicitud_prestamo sp
           JOIN equipo e ON e.id = sp.equipo_id
           JOIN entrega_equipo ee ON ee.solicitud_prestamo_id = sp.id
          WHERE sp.id = $1`,
        [requestId]
      );
      assert.deepEqual(
        [active.rows[0].estado, active.rows[0].equipo_estado, active.rows[0].condicion_entrega],
        ['activo', 'prestado', 'Equipo entregado en buen estado']
      );

      const returned = await request(adminApp.app)
        .post(`/entrega-equipos/${requestId}/recibir`)
        .send({
          condicion_devolucion: 'Equipo recibido en buen estado',
          lista_componentes: ['Cable de poder', 'Manual'],
        });
      assert.equal(returned.status, 200);
      assert.equal(returned.body.success, true);
      const completed = await fixture.db.query(
        `SELECT sp.estado, e.estado AS equipo_estado, ee.fecha_devolucion_real,
                ee.condicion_devolucion, ee.lista_componentes
           FROM solicitud_prestamo sp
           JOIN equipo e ON e.id = sp.equipo_id
           JOIN entrega_equipo ee ON ee.solicitud_prestamo_id = sp.id
          WHERE sp.id = $1`,
        [requestId]
      );
      assert.equal(completed.rows[0].estado, 'finalizado');
      assert.equal(completed.rows[0].equipo_estado, 'disponible');
      assert.ok(completed.rows[0].fecha_devolucion_real);
      assert.equal(completed.rows[0].condicion_devolucion, 'Equipo recibido en buen estado');
      assert.deepEqual(completed.rows[0].lista_componentes, ['Cable de poder', 'Manual']);

      const rejectedReservation = await request(studentApp.app).post('/solicitudes/crear').send({
        equipo_id: '5',
        fecha_inicio: '2999-12-31T10:00',
        fecha_fin: '2999-12-31T11:00',
        justificacion_academica: 'Practica de laboratorio de ciencias',
        categoria_practica: 'academica',
        firma_digital: 'Acepto el reglamento',
      });
      assert.equal(rejectedReservation.status, 200);
      const rejectedId = rejectedReservation.body.solicitud.id;

      const rejection = await request(adminApp.app)
        .post(`/gestion-solicitudes/${rejectedId}/rechazar`)
        .send({ motivo_rechazo: 'El equipo se requiere para otra práctica' });
      assert.equal(rejection.status, 200);
      assert.equal(rejection.body.success, true);
      const rejected = await fixture.db.query(
        'SELECT estado, motivo_rechazo FROM solicitud_prestamo WHERE id = $1',
        [rejectedId]
      );
      assert.deepEqual(
        [rejected.rows[0].estado, rejected.rows[0].motivo_rechazo],
        ['rechazado', 'El equipo se requiere para otra práctica']
      );
    } finally {
      adminApp?.restore();
      studentApp?.restore();
      await fixture.cleanup();
    }
  }
);
